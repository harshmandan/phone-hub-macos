#!/usr/bin/env python3
"""Generate nc_advert.h: the Nearby Connections BLE advertisement a Chromebook
emits during Quick Start, pointing the phone at the Mac's Bluetooth Classic MAC.

Formats follow google/nearby (connections/implementation/):
  ble_advertisement.cc                (PCP layer, carries bluetooth_mac_address)
  mediums/ble/ble_advertisement.cc    (medium layer, served from a GATT characteristic)
  mediums/ble/ble_advertisement_header.cc + bloom_filter.cc (FEF3 service-data header)
and the endpoint info from Chromium target_device_connection_broker_impl.cc.

The phone sees the header, GATT-reads the full advertisement from the C6, finds
the Mac's MAC in it, and opens RFCOMM to the Mac (p2p_cluster_pcp_handler.cc).
"""
import base64, hashlib, struct, sys

SERVICE_ID = "com.google.android.gms.smartdevice.NC_ID"
ADVERTISING_ID = bytes.fromhex("112233445566")   # == firmware ADVERTISING_ID
ENDPOINT_ID = b"QSMC"                             # == btserve's fixed endpoint id
MAC = bytes.fromhex(sys.argv[1].replace(":", "") if len(sys.argv) > 1 else "F84D897ED8E7")
DISPLAY_NAME = b"Chromebook"
DEVICE_TOKEN = hashlib.sha256(b"phonehub").digest()[:2]
DUMMY_SERVICE_ID = b"phonehubdm"                  # anonymizing dummy, any bytes


def sha(b, n):
    return hashlib.sha256(b).digest()[:n]


def murmur3_x64_128_low64(data: bytes, seed: int = 0) -> int:
    M = (1 << 64) - 1
    c1, c2 = 0x87C37B91114253D5, 0x4CF5AD432745937F
    rotl = lambda x, r: ((x << r) | (x >> (64 - r))) & M

    def fmix(k):
        k ^= k >> 33; k = (k * 0xFF51AFD7ED558CCD) & M
        k ^= k >> 33; k = (k * 0xC4CEB9FE1A85EC53) & M
        return k ^ (k >> 33)

    h1 = h2 = seed
    n = len(data) // 16
    for i in range(n):
        k1, k2 = struct.unpack_from("<QQ", data, i * 16)
        k1 = (k1 * c1) & M; k1 = rotl(k1, 31); k1 = (k1 * c2) & M; h1 ^= k1
        h1 = rotl(h1, 27); h1 = (h1 + h2) & M; h1 = (h1 * 5 + 0x52DCE729) & M
        k2 = (k2 * c2) & M; k2 = rotl(k2, 33); k2 = (k2 * c1) & M; h2 ^= k2
        h2 = rotl(h2, 31); h2 = (h2 + h1) & M; h2 = (h2 * 5 + 0x38495AB5) & M
    tail = data[n * 16:]
    k1 = k2 = 0
    for i in range(len(tail) - 1, 7, -1):
        k2 ^= tail[i] << ((i - 8) * 8)
    if len(tail) > 8:
        k2 = (k2 * c2) & M; k2 = rotl(k2, 33); k2 = (k2 * c1) & M; h2 ^= k2
    for i in range(min(len(tail), 8) - 1, -1, -1):
        k1 ^= tail[i] << (i * 8)
    if tail:
        k1 = (k1 * c1) & M; k1 = rotl(k1, 31); k1 = (k1 * c2) & M; h1 ^= k1
    h1 ^= len(data); h2 ^= len(data)
    h1 = (h1 + h2) & M; h2 = (h2 + h1) & M
    h1 = fmix(h1); h2 = fmix(h2)
    h1 = (h1 + h2) & M
    return h1  # lower 64 bits of the 128-bit result


def s32(x):
    x &= 0xFFFFFFFF
    return x - (1 << 32) if x & 0x80000000 else x


def bloom(items, nbytes=10):
    bits = [0] * (nbytes * 8)
    for s in items:
        h64 = murmur3_x64_128_low64(s)
        h1, h2 = s32(h64), s32(h64 >> 32)
        for i in range(1, 6):
            c = s32(h1 + i * h2)
            if c < 0:
                c = ~c
            bits[c % len(bits)] = 1
    return bytes(sum(bits[8 * k + j] << j for j in range(8)) for k in range(nbytes))


# Endpoint info, exactly as Chromium GenerateEndpointInfo builds it.
adv = bytes([5, 8]) + base64.urlsafe_b64encode(ADVERTISING_ID).rstrip(b"=").ljust(10, b"\0")
adv += bytes([1, 0])
adv = adv.ljust(60, b"\0")
endpoint_info = bytes([1]) + DISPLAY_NAME + b"\0" + base64.b64encode(adv).rstrip(b"=")
assert len(endpoint_info) <= 131

sid_hash = sha(SERVICE_ID.encode(), 3)
# PCP-layer advertisement: v1 | P2P_POINT_TO_POINT(3), non-fast form.
pcp = bytes([(1 << 5) | 3]) + sid_hash + ENDPOINT_ID + bytes([len(endpoint_info)]) + endpoint_info
pcp += MAC + b"\x00" + b"\x00"   # bt mac, uwb len 0, extra field (no WebRTC)
# Medium-layer advertisement: version 2, socket version 2, not fast.
medium = bytes([(2 << 5) | (2 << 2)]) + sid_hash + struct.pack(">I", len(pcp)) + pcp + DEVICE_TOKEN
# Header: v2, no extended-adv flag, 1 slot; bloom; chained adv hash; psm 0.
h = sha(DUMMY_SERVICE_ID, 4)
h = sha(h + medium, 4)
header = bytes([(2 << 5) | 1]) + bloom([DUMMY_SERVICE_ID, SERVICE_ID.encode()]) + h + b"\x00\x00"
assert len(header) == 17


def carr(name, b):
    body = ", ".join(f"0x{x:02x}" for x in b)
    return f"static const uint8_t {name}[{len(b)}] = {{ {body} }};\n"


out = ("// Generated by gen_nc_advert.py — do not edit.\n"
       f"// service {SERVICE_ID}, endpoint {ENDPOINT_ID.decode()}, Mac BT {MAC.hex(':').upper()}\n"
       "#pragma once\n#include <stdint.h>\n"
       + carr("NC_HEADER", header) + carr("NC_GATT_ADVERTISEMENT", medium))
open(__file__.replace("gen_nc_advert.py", "nc_advert.h"), "w").write(out)
print("endpoint_info", endpoint_info)
print("header", header.hex())
print("medium", len(medium), medium.hex())

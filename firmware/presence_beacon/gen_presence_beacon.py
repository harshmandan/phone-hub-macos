#!/usr/bin/env python3
"""Generate presence_beacon.ino — a XIAO ESP32-C6 sketch that advertises the
Mac Chromebook's Better Together background presence beacon: BLE service FE50
with service data = the rotating 2-byte EID derived from our beacon seeds.

The phone (which holds our beacon_seeds via DeviceSync) scans for this EID; a
match tells GmsCore the Chromebook is present, so it opens the secure_channel
RFCOMM accept window — which is what lets the Mac then connect out.

EID = SHA256(seed.data || big-endian uint64(periodStart))[:2], 15-min periods,
period anchored at the seed's start time (ble background_eid_generator.cc). The
C6 computes it itself (mbedtls SHA256) and rotates; it keeps time as
BOOT_EPOCH_MS + millis(), so flash within ~20 min of generating (the phone
tolerates ±2 periods).

Usage:  ./gen_presence_beacon.py [path/to/device_keys.json]
"""
import json
import sys
import time

KEYS = sys.argv[1] if len(sys.argv) > 1 else "../../probe/device_keys.json"


def main() -> None:
    ks = json.load(open(KEYS))
    now = int(time.time() * 1000)
    seeds = ks.get("macBeaconSeeds") or []
    active = [s for s in seeds if s["startMs"] <= now <= s["endMs"]]
    if not active:
        print("no active macBeaconSeed; run upload_host_metadata.py first")
        sys.exit(1)
    s = active[0]
    seed = bytes.fromhex(s["dataHex"])
    seed_c = ", ".join(f"0x{b:02x}" for b in seed)

    ino = f"""// Chromebook Better Together PRESENCE beacon — Seeed XIAO ESP32-C6
// GENERATED by gen_presence_beacon.py — do not edit by hand.
//
// Advertises BLE service FE50 with service data = our rotating 2-byte EID, so
// the phone (holding our beacon_seeds) recognizes the Chromebook as present and
// opens its secure_channel RFCOMM window. Non-connectable background advert.
//
// EID = SHA256(SEED || big-endian uint64(periodStart))[:2], 15-min periods
// anchored at SEED_START_MS. Time = BOOT_EPOCH_MS + millis(); flash promptly.
#include <NimBLEDevice.h>
#include "mbedtls/sha256.h"

static const uint8_t  SEED[32] = {{ {seed_c} }};
static const int64_t  SEED_START_MS = {s['startMs']}LL;
static const int64_t  BOOT_EPOCH_MS = {now}LL;   // when generated; +millis() advances
static const int64_t  PERIOD_MS = 15LL * 60LL * 1000LL;

static NimBLEExtAdvertising* adv;

// Flags + Service Data (AD type 0x16) for UUID FE50 (LE) + 2-byte EID.
static uint8_t adv_raw[] = {{
  0x02, 0x01, 0x06,
  0x05, 0x16, 0x50, 0xFE, 0x00, 0x00
}};

static void computeEid(int64_t nowMs, uint8_t out[2]) {{
  int64_t ps = SEED_START_MS + ((nowMs - SEED_START_MS) / PERIOD_MS) * PERIOD_MS;
  uint8_t buf[40];
  memcpy(buf, SEED, 32);
  for (int i = 0; i < 8; i++) buf[32 + i] = (uint8_t)(ps >> (8 * (7 - i)));
  uint8_t h[32];
  mbedtls_sha256(buf, 40, h, 0);
  out[0] = h[0];
  out[1] = h[1];
}}

static void advertiseEid() {{
  int64_t nowMs = BOOT_EPOCH_MS + (int64_t)millis();
  uint8_t eid[2];
  computeEid(nowMs, eid);
  adv_raw[7] = eid[0];
  adv_raw[8] = eid[1];
  NimBLEExtAdvertisement a;
  a.setLegacyAdvertising(true);
  a.setConnectable(false);
  a.setScannable(false);
  a.addData(adv_raw, sizeof(adv_raw));
  adv->stop(0);
  adv->setInstanceData(0, a);
  adv->start(0);
  Serial.printf("FE50 EID = %02x%02x (now=%lld)\\n", eid[0], eid[1], (long long)nowMs);
}}

void setup() {{
  Serial.begin(115200);
  delay(300);
  NimBLEDevice::init("");
  adv = NimBLEDevice::getAdvertising();
  advertiseEid();
  Serial.println("Up: FE50 Chromebook presence beacon.");
}}

void loop() {{
  delay(30000);
  advertiseEid();
}}
"""
    with open("presence_beacon.ino", "w") as f:
        f.write(ino)
    print("wrote presence_beacon.ino")
    print(f"  active seed {s['dataHex'][:12]}…  BOOT_EPOCH_MS={now} ({time.strftime('%H:%M:%S')})")
    print("  flash within ~20 min so the embedded clock stays close.")


if __name__ == "__main__":
    main()
